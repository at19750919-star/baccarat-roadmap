const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
let chromium;
try { ({ chromium } = require('playwright')); }
catch { ({ chromium } = require(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'))); }

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    page.setDefaultTimeout(8000);
    await page.route('https://**', route => route.fulfill({ body: '' }));
    const url = pathToFileURL(path.join(__dirname, '../tv.html')).href;
    await page.goto(url, { waitUntil: 'domcontentloaded' });
    await page.evaluate(() => localStorage.clear());
    await page.reload({ waitUntil: 'domcontentloaded' });
    const board = page.locator('.tv-table-board').first();
    const background = () => board.evaluate(el => ({ image: getComputedStyle(el).backgroundImage, base: el.dataset.tvEditBaseBackground, light: el.dataset.tvEditLight, inline: el.style.background }));
    await page.click('#tvEditToggle');
    await board.dispatchEvent('click');
    await page.fill('#tvEditBackground', '#123456');
    await page.locator('#tvEditBackground').press('Tab');
    assert.equal((await background()).image, 'none');
    await page.check('#tvEditLightEnabled');
    let state = await background();
    assert.match(state.image, /^radial-gradient/);
    assert.equal(state.base, 'rgb(18, 52, 86)');
    await page.locator('#tvEditLightX').fill('75');
    await page.locator('#tvEditLightY').fill('20');
    await page.locator('#tvEditLightStrength').fill('80');
    state = await background();
    assert.match(state.image, /at 75% 20%/);
    assert.equal(state.light, '75,20,80');
    assert.equal(await page.locator('#tvEditLightStrength + output').textContent(), '80%');
    await page.click('#tvEditBgGradient');
    await page.fill('#tvEditGradientStart', '#112233');
    await page.fill('#tvEditGradientEnd', '#AABBCC');
    await page.click('[data-bg-angle="90"]');
    state = await background();
    assert.match(state.image, /^radial-gradient.*linear-gradient/s);
    assert.match(state.base, /90deg/);
    assert.equal(await page.locator('#tvEditBgGradient').getAttribute('aria-pressed'), 'true');
    const beforePicker = await background();
    await page.locator('#tvEditGradientStart').click();
    await page.locator('.cp-tab-btn[data-tab="swatches"]').click();
    await page.locator('.cp-swatches-grid [data-color="#f44336"]').click();
    await page.waitForFunction(() => document.querySelector('.tv-table-board').dataset.tvEditBaseBackground.includes('#F44336'));
    await page.keyboard.press('Escape');
    await page.waitForFunction(expected => document.querySelector('.tv-table-board').dataset.tvEditBaseBackground === expected, beforePicker.base);
    assert.equal((await background()).inline, beforePicker.inline);
    assert.equal(await page.locator('#tvEditGradientStart').inputValue(), '#112233');
    await page.click('#tvEditSave');
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('tv-edit-mode:settings')));
    assert.equal(saved['tv-table-board'].light, '75,20,80');
    assert.match(saved['tv-table-board'].background, /90deg/);
    assert.doesNotMatch(saved['tv-table-board'].background, /radial-gradient/);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => document.querySelector('.tv-table-board')?.dataset.tvEditLight === '75,20,80');
    await page.click('#tvEditToggle');
    await board.dispatchEvent('click');
    assert.equal(await page.locator('#tvEditLightEnabled').isChecked(), true);
    assert.equal(await page.locator('#tvEditLightX').inputValue(), '75');
    assert.equal(await page.locator('#tvEditLightY').inputValue(), '20');
    assert.equal(await page.locator('#tvEditLightStrength').inputValue(), '80');
    assert.equal(await page.locator('#tvEditBgGradient').getAttribute('aria-pressed'), 'true');
    await page.uncheck('#tvEditLightEnabled');
    assert.doesNotMatch((await background()).image, /radial-gradient/);
    page.once('dialog', dialog => dialog.accept());
    await page.click('#tvEditCancel');
    await page.waitForFunction(() => document.querySelector('.tv-table-board')?.dataset.tvEditLight === '75,20,80');
    await page.click('#tvEditToggle');
    await board.dispatchEvent('click');
    await page.click('#tvEditReset');
    assert.equal((await background()).light, undefined);
    assert.equal((await background()).inline, '');
    await page.check('#tvEditLightEnabled');
    const colorField = page.locator('#tvEditSolidColor');
    await colorField.fill('#445566');
    await colorField.press('Tab');
    await page.waitForFunction(() => {
      const board = document.querySelector('.tv-table-board');
      const base = (board?.dataset.tvEditBaseBackground || '').toUpperCase();
      return base.includes('#445566') || getComputedStyle(board).backgroundColor === 'rgb(68, 85, 102)';
    });
    assert.match((await background()).image, /^radial-gradient/);
    assert.equal(await board.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(68, 85, 102)');
    console.log('PASS: light position/strength, single and gradient layering, save/reload, cancel, reset');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
